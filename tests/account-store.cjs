const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('C:/Users/19332/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root = path.resolve(__dirname, '..');
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  try {
    const context = await browser.newContext();
    const page = await context.newPage();
    await page.route('http://localhost/account-test', route => route.fulfill({ contentType: 'text/html', body: '<div id="account-card"></div>' }));
    async function boot(target = page) {
      await target.route('http://localhost/account-test', route => route.fulfill({ contentType: 'text/html', body: '<div id="account-card"></div>' }));
      await target.goto('http://localhost/account-test');
      for (const name of ['profile-store.js', 'account-ui.js']) await target.addScriptTag({ content: fs.readFileSync(path.join(root, 'assets', name), 'utf8') });
      await target.evaluate(async () => {
        window.state = { tasks: ['guest'], focusRecords: [{ minutes: 25, date: '2026-10-18' }], house: { toy: 'guest' } };
        window.allowSwitch = true;
        await AccountManager.init({ getState: () => state, setState: data => { state = data; }, createDefaultState: () => ({ tasks: [], focusRecords: [], house: {} }), canSwitch: () => allowSwitch });
      });
    }
    await boot();
    await page.evaluate(() => AccountManager.register(' Alice ', 'alice-secret-123'));
    assert.equal(await page.evaluate(() => state.tasks[0]), 'guest', 'first account migrates guest');
    await page.evaluate(() => { state.tasks = ['Alice only']; state.house.toy = 'A'; AccountManager.persist(); });
    await page.evaluate(() => AccountManager.register('Bob', 'bob-secret-123'));
    assert.deepEqual(await page.evaluate(() => state.tasks), [], 'second account starts empty');
    await page.evaluate(() => { state.tasks = ['Bob only']; AccountManager.persist(); });
    await page.evaluate(async () => { try { await AccountManager.login('alice', 'wrong-password'); } catch {} });
    assert.deepEqual(await page.evaluate(() => state.tasks), ['Bob only']);
    assert.equal(await page.evaluate(() => AccountManager.activeUser.username), 'Bob');
    await page.evaluate(() => AccountManager.login('ＡＬＩＣＥ', 'alice-secret-123'));
    assert.deepEqual(await page.evaluate(() => state.tasks), ['Alice only']);
    assert.equal(await page.evaluate(() => state.house.toy), 'A');
    await page.evaluate(async () => { try { await AccountManager.register('ALICE', 'new-password'); } catch {} });
    assert.equal(await page.evaluate(() => AccountManager.activeUser.username), 'Alice');
    const saved = await page.evaluate(() => JSON.stringify(localStorage));
    assert.ok(!saved.includes('alice-secret-123') && !saved.includes('bob-secret-123'), 'no plaintext credentials');
    await boot();
    assert.equal(await page.evaluate(() => AccountManager.activeUser.username), 'Alice');
    assert.deepEqual(await page.evaluate(() => state.tasks), ['Alice only'], 'refresh restores snapshot');
    await page.evaluate(() => AccountManager.logout());
    assert.deepEqual(await page.evaluate(() => state.tasks), ['guest'], 'guest stays separate');
    await page.evaluate(() => AccountManager.login('Bob', 'bob-secret-123'));
    assert.deepEqual(await page.evaluate(() => state.tasks), ['Bob only']);
    await page.evaluate(async () => { allowSwitch = false; try { await AccountManager.logout(); } catch {} });
    assert.equal(await page.evaluate(() => AccountManager.activeUser.username), 'Bob', 'running focus/edit prevents switching');
    await page.evaluate(() => { allowSwitch = true; AccountManager.show(); });
    await page.locator('input[name="username"]').fill('alice');
    await page.locator('input[name="password"]').fill('wrong-password');
    await page.getByRole('button', { name: '登录账号', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.account-dialog .account-error').textContent.includes('不正确'));
    assert.equal(await page.locator('input[name="password"]').inputValue(), '');
    await page.getByRole('button', { name: '关闭', exact: true }).click();
    await page.evaluate(() => AccountManager.login('alice', 'alice-secret-123'));
    await page.evaluate(() => AccountManager.showHistory());
    assert.match(await page.locator('.account-dialog').innerText(), /25 分钟/);
    await page.getByRole('button', { name: '关闭', exact: true }).click();
    const aliceKey = await page.evaluate(() => AccountManager.scopeKey('draft'));
    await page.evaluate(() => AccountManager.login('Bob', 'bob-secret-123'));
    assert.notEqual(await page.evaluate(() => AccountManager.scopeKey('draft')), aliceKey, 'draft keys are scoped');
    const credentials = await page.evaluate(() => JSON.parse(localStorage.getItem('qingpeiban.profiles.v1')).users.map(user => user.credential));
    assert.equal(credentials[0].algorithm, 'PBKDF2-SHA-256');
    assert.ok(credentials[0].iterations >= 210000);
    assert.notEqual(credentials[0].salt, credentials[1].salt);
    await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('quota'); }; state.tasks = ['unsaved']; AccountManager.persist(); });
    assert.match(await page.locator('#account-card').innerText(), /保存失败/);
    await page.evaluate(async () => { try { await AccountManager.logout(); } catch {} });
    assert.equal(await page.evaluate(() => AccountManager.activeUser.username), 'Bob', 'save error blocks account switch');
    await page.evaluate(() => location.reload());
    await boot();
    assert.deepEqual(await page.evaluate(() => state.tasks), ['Bob only'], 'failed save leaves prior snapshot intact');
    await page.evaluate(() => localStorage.setItem('qingpeiban.profiles.v1', '{broken'));
    await boot();
    assert.match(await page.locator('#account-card').innerText(), /保存失败/);
    assert.equal(await page.evaluate(() => localStorage.getItem('qingpeiban.profiles.v1')), '{broken', 'corrupt storage is preserved');
    await page.evaluate(() => localStorage.clear());
    await boot();
    await page.evaluate(() => AccountManager.register('Alice', 'alice-secret-123'));
    const second = await page.context().newPage();
    await boot(second);
    await page.evaluate(() => AccountManager.register('Bob', 'bob-secret-123'));
    await page.evaluate(() => { state.tasks = ['Bob latest']; AccountManager.persist(); });
    await second.evaluate(() => { state.tasks = ['Alice stale']; AccountManager.persist(); });
    assert.equal(await second.evaluate(() => AccountManager.activeUser.username), 'Alice', 'another tab does not change page identity');
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('qingpeiban.profiles.v1')).users.length), 2, 'stale tab cannot delete new account');
    assert.match(await second.locator('#account-card').innerText(), /另一页面|其他页面/);
    await boot(second);
    await second.evaluate(() => AccountManager.login('Alice', 'alice-secret-123'));
    assert.equal(await page.evaluate(() => AccountManager.activeUser.username), 'Bob');
    await page.evaluate(() => { state.tasks = ['Bob after other tab login']; AccountManager.persist(); });
    // The other page saved Bob while switching away: stale Bob must detect the revision conflict.
    assert.match(await page.locator('#account-card').innerText(), /另一页面|其他页面/);
    await second.evaluate(() => { state.tasks = ['Alice latest']; AccountManager.persist(); });
    const third = await page.context().newPage(); await boot(third);
    await second.evaluate(() => { state.tasks = ['Alice newest']; AccountManager.persist(); });
    await third.evaluate(() => { state.tasks = ['Alice stale overwrite']; AccountManager.persist(); });
    const users = await second.evaluate(() => JSON.parse(localStorage.getItem('qingpeiban.profiles.v1')).users);
    assert.deepEqual(users.find(user => user.username === 'Alice').snapshot.tasks, ['Alice newest']);
    assert.deepEqual(users.find(user => user.username === 'Bob').snapshot.tasks, ['Bob latest']);
    assert.match(await third.locator('#account-card').innerText(), /另一页面|其他页面/);
    await third.close(); await second.close();
    console.log('PASS: migration, isolation, normalization, credentials, refresh, guest, UI errors/history, focus lock, scoped drafts, save failure and corrupt storage');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
